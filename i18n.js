function storedLang() { try { return JSON.parse(localStorage.getItem("mhm_uiLang")); } catch (e) { return null; } }
let LANG = UI_LANGS[storedLang()] ? storedLang() : "he";

function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) != null ? I18N[LANG][key] : (I18N.he[key] != null ? I18N.he[key] : key);
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
  return s;
}

function applyI18n(root) {
  root = root || document;
  root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-ph]").forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll("[data-i18n-aria]").forEach(el => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  document.documentElement.lang = LANG;
  document.documentElement.dir = UI_LANGS[LANG].dir;
  document.title = t("h001");
}

function setLang(l) {
  if (!UI_LANGS[l]) return;
  LANG = l;
  try { localStorage.setItem("mhm_uiLang", JSON.stringify(l)); } catch (e) {}
  applyI18n();
}
function hasChosenLang() { return !!UI_LANGS[storedLang()]; }
